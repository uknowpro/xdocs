"""Compile the editable part of 'terraform providers schema -json' for offline use."""
import base64
import gzip
import hashlib
import json
import sys
from pathlib import Path

shapes = []
index = {}
def intern(value):
    key = json.dumps(value, separators=(",", ":"), ensure_ascii=True)
    if key not in index:
        index[key] = len(shapes)
        shapes.append(value)
    return index[key]

def shape(block):
    fields = {}
    for key, a in sorted(block.get("attributes", {}).items()):
        if not (a.get("optional") or a.get("required")):
            continue
        nested = a.get("nested_type")
        typ = a.get("type", "dynamic")
        if nested:
            typ = [nested["nesting_mode"], shape(nested)]
        fields[key] = [typ, bool(a.get("required")), bool(a.get("sensitive"))]
    for key, b in sorted(block.get("block_types", {}).items()):
        fields[key] = [[b["nesting_mode"], shape(b["block"])], bool(b.get("min_items")), False]
    return intern(fields)

resources = {}
for provider, data in sorted(json.loads(Path(sys.argv[1]).read_text())["provider_schemas"].items()):
    for kind, schema in sorted(data.get("resource_schemas", {}).items()):
        key = "beta_" + kind if provider.endswith("/google-beta") else kind
        resources[key] = shape(schema["block"])

# Stable fingerprints include nested definitions, independent of their indexes.
hashes = []
for fields in shapes:
    normalized = {}
    for name, (typ, required, sensitive) in fields.items():
        if isinstance(typ, list) and isinstance(typ[1], int):
            typ = [typ[0], hashes[typ[1]]]
        normalized[name] = [typ, required, sensitive]
    hashes.append(hashlib.sha256(json.dumps(normalized,sort_keys=True).encode()).hexdigest()[:20])
payload = json.dumps([resources, shapes, hashes], separators=(",", ":")).encode()
encoded = base64.b64encode(gzip.compress(payload, mtime=0)).decode()
# Preserve removed kinds for old canvases. Publish field-level differences only
# after comparing with the previously shipped snapshot.
output = Path(sys.argv[2])
history_file = output.with_name("schema-changes.mjs")
def read_module(file):
    return json.loads(file.read_text().split("export default ", 1)[1].strip().removesuffix(";"))
history = read_module(history_file) if history_file.exists() else {"changes": {}, "retired": []}
if output.exists():
    old_resources, old_shapes, old_hashes = json.loads(gzip.decompress(base64.b64decode(read_module(output))))
    added = sorted(resources.keys() - old_resources.keys())
    removed = sorted(old_resources.keys() - resources.keys())
    changed = {}
    def signature(field, hashes):
        typ, req, secret = field
        if isinstance(typ, list) and isinstance(typ[1], int):
            typ = [typ[0], hashes[typ[1]]]
        return [typ, req, secret]
    for kind in resources.keys() & old_resources.keys():
        before, after = old_resources[kind], resources[kind]
        if old_hashes[before] == hashes[after]:
            continue
        previous, current = old_shapes[before], shapes[after]
        changed[kind] = {
            "from": old_hashes[before],
            "added": sorted(current.keys() - previous.keys()),
            "removed": sorted(previous.keys() - current.keys()),
            "changed": sorted(k for k in current.keys() & previous.keys()
                              if signature(current[k], hashes) != signature(previous[k], old_hashes))
        }
    if added or removed or changed:
        history = {"added": added, "removed": removed, "changes": changed,
                   "retired": sorted((set(history["retired"]) | set(removed)) - resources.keys())}
        print(f"Managed resources: +{len(added)} -{len(removed)}, changed schemas: {len(changed)}")
history_file.write_text("export default " + json.dumps(history, sort_keys=True, separators=(",", ":")) + ";\n")
Path(sys.argv[2]).write_text("// Generated by scripts/compile-resource-schema.py\nexport default "+json.dumps(encoded)+";\n")
